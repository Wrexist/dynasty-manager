/**
 * Squad-route report — does buying packs outpace playing football?
 *
 * The design brief's standing worry is that Dynasty Manager degenerates into
 * "open pack → sell → open pack", with the football underneath it reduced to
 * scenery. That is a real risk and it is NOT a question anyone should answer
 * from intuition, so this measures it instead of guessing.
 *
 * The question, made concrete: for the SAME club, how much squad strength
 * arrives per route?
 *
 *   PACKS     — what a tier deals, and how much of it actually beats the XI
 *               you already have.
 *   TRANSFERS — what the club's own budget buys at market prices.
 *
 * "Squad strength" is measured two ways on purpose, because they disagree and
 * the disagreement is the interesting part:
 *
 *   BOOK VALUE  — the market price of what the pack dealt. Flatters packs:
 *                 five 78s look like a fortune and may not improve the team
 *                 at all.
 *   XI UPGRADES — cards that out-rate the club's current best in that
 *                 position. This is the honest one. A card that does not
 *                 crack the XI has not built anything.
 *
 * Gated behind VITEST_ROUTES=1 so normal runs don't pay the cost:
 *
 *   VITEST_ROUTES=1 npx vitest run squadRouteReport
 *
 * A REPORT, not a gate. It asserts only that the markdown was written — the
 * numbers are for a human to read before touching a single balance value.
 */
import { describe, it, expect } from 'vitest';
import { writeFileSync, mkdirSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import type { Player } from '@/types/game';
import { useGameStore } from '@/store/gameStore';
import { generatePackContents } from '@/utils/packGeneration';
import { PACK_STOREFRONT_ORDER, PACK_TIER_MAP } from '@/config/packs';
import type { PackTierKey } from '@/types/game';

const RUN = process.env.VITEST_ROUTES === '1';
const SAMPLES = 200;

/** Clubs spanning the money range, so the answer isn't only true for a giant. */
const REFERENCE_CLUBS = [
  { id: 'manchester-city', label: 'Elite' },
  { id: 'celtic', label: 'Mid' },
  { id: 'luton-town', label: 'Lower' },
];

const money = (n: number) => `£${(n / 1_000_000).toFixed(1)}M`;
const mean = (xs: number[]) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : 0);
function median(xs: number[]): number {
  if (!xs.length) return 0;
  const s = [...xs].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
}

/** Best overall per position in a squad — the bar a pull has to clear. */
function bestByPosition(playerIds: string[], all: Record<string, Player>): Map<string, number> {
  const best = new Map<string, number>();
  for (const id of playerIds) {
    const p = all[id];
    if (!p) continue;
    if (p.overall > (best.get(p.position) ?? 0)) best.set(p.position, p.overall);
  }
  return best;
}

/** Cards that would displace the current best in their position. Mirrors
 *  `computeSquadImprovement` in PacksPage — same definition the reveal screen
 *  uses to badge an upgrade, so the report and the game agree on the word. */
function countXiUpgrades(pulled: Player[], best: Map<string, number>): number {
  let n = 0;
  for (const p of pulled) {
    const bar = best.get(p.position) ?? 0;
    if (bar > 0 && p.overall > bar) n += 1;
  }
  return n;
}

describe('squad-route report', () => {
  it.skipIf(!RUN)('measures packs against the club\'s own budget', () => {
    const lines: string[] = [];
    lines.push('# Squad routes — packs vs football');
    lines.push('');
    lines.push(`Generated by \`src/test/squadRouteReport.test.ts\` · ${SAMPLES} opens per tier per club.`);
    lines.push('');
    lines.push('**Read XI upgrades, not book value.** Book value is what the cards are');
    lines.push('worth; XI upgrades are what they actually change. A pack that deals');
    lines.push('£40M of players who all sit on the bench has built nothing.');
    lines.push('');

    for (const club of REFERENCE_CLUBS) {
      useGameStore.getState().initGame(club.id);
      const state = useGameStore.getState();
      const clubData = state.clubs[state.playerClubId];
      if (!clubData) continue;

      const squad = clubData.playerIds.map(id => state.players[id]).filter(Boolean) as Player[];
      const best = bestByPosition(clubData.playerIds, state.players);
      const xi = [...squad].sort((a, b) => b.overall - a.overall).slice(0, 11);
      const xiAvg = mean(xi.map(p => p.overall));
      const budget = clubData.budget;

      lines.push(`## ${clubData.name} (${club.label})`);
      lines.push('');
      lines.push(`- Transfer budget: **${money(budget)}**`);
      lines.push(`- Best XI average: **${xiAvg.toFixed(1)} OVR**`);
      lines.push(`- Squad size: ${squad.length}`);
      lines.push('');
      lines.push('| Pack | $ | Cards | Best OVR (med) | Book value | Book per $ | XI upgrades | Cost of 1 upgrade |');
      lines.push('|---|---:|---:|---:|---:|---:|---:|---:|');

      for (const tierKey of PACK_STOREFRONT_ORDER) {
        const tier = PACK_TIER_MAP[tierKey];
        if (!tier) continue;
        // `iapPriceDisplay` is the planned tier ('$4.99'); the real price comes
        // from the store at runtime, so this is a planning figure, not a fact.
        const price = usdOf(tier.iapPriceDisplay);

        const bestOvrs: number[] = [];
        const books: number[] = [];
        const upgrades: number[] = [];

        for (let i = 0; i < SAMPLES; i++) {
          const pulled = generatePackContents(tierKey, state.season, {
            freeOpen: price === 0,
            streak: 1,
          });
          if (!pulled.length) continue;
          bestOvrs.push(Math.max(...pulled.map(p => p.overall)));
          books.push(pulled.reduce((s, p) => s + (p.value || 0), 0));
          upgrades.push(countXiUpgrades(pulled, best));
        }

        const avgUpgrades = mean(upgrades);
        // The number that matters commercially AND for game health: what does
        // it cost to actually improve the team by one player?
        const costPerUpgrade = avgUpgrades > 0 && price > 0
          ? `$${(price / avgUpgrades).toFixed(2)}`
          : avgUpgrades > 0 ? 'free' : '—';

        lines.push(
          `| ${tier.label} | ${price ? `$${price.toFixed(2)}` : 'free'} | ${pulledCount(tierKey)} `
          + `| ${median(bestOvrs).toFixed(0)} `
          + `| ${money(mean(books))} `
          + `| ${price ? money(mean(books) / price) : '—'} `
          + `| ${avgUpgrades.toFixed(2)} `
          + `| ${costPerUpgrade} |`,
        );
      }

      lines.push('');
      // The headline comparison: one pack's book value against the entire
      // budget the football game gives you for the season.
      const goldBook = sampleBook('gold', state.season);
      lines.push(`One Champions pack ($2.99) deals ${money(goldBook)} of book value — `
        + `**${((goldBook / Math.max(1, budget)) * 100).toFixed(0)}%** of this club's whole transfer budget.`);
      lines.push('');
    }

    lines.push('## How to read this');
    lines.push('');
    lines.push('- If **XI upgrades** per paid pack is high for a mid or lower club, packs');
    lines.push('  are the dominant squad-building route and the football underneath is');
    lines.push('  decoration. That is the failure mode to avoid.');
    lines.push('- If **book value per $** dwarfs the season budget but **XI upgrades**');
    lines.push('  stays near zero, packs are selling cash rather than strength — a');
    lines.push('  different problem, and the one the quick-sell taper governs.');
    lines.push('- An elite club should see near-zero XI upgrades from cheap packs. If it');
    lines.push('  does not, the guaranteed floors are too high for the top of the game.');
    lines.push('');

    const out = join(process.cwd(), 'docs', 'squad-routes-report.md');
    if (!existsSync(dirname(out))) mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, lines.join('\n'), 'utf-8');
    console.log(`\n${lines.join('\n')}\n`);
    expect(existsSync(out)).toBe(true);
  }, 120_000);
});

/** Card count a tier deals, for the table. */
function pulledCount(tierKey: PackTierKey): number {
  return PACK_TIER_MAP[tierKey]?.cards ?? 0;
}

/** Parse the planned USD tier off `iapPriceDisplay`. Free tiers have none. */
function usdOf(display: string | undefined): number {
  if (!display) return 0;
  const n = Number(display.replace(/[^0-9.]/g, ''));
  return Number.isFinite(n) ? n : 0;
}

/** Mean book value of one tier's open, sampled independently for the headline. */
function sampleBook(tierKey: PackTierKey, season: number): number {
  const books: number[] = [];
  for (let i = 0; i < SAMPLES; i++) {
    const pulled = generatePackContents(tierKey, season, {});
    books.push(pulled.reduce((s, p) => s + (p.value || 0), 0));
  }
  return mean(books);
}
