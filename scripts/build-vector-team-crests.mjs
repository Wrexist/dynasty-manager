import fs from 'node:fs';
import vm from 'node:vm';
import crypto from 'node:crypto';
import ts from 'typescript';
import { createVectorCrest } from './lib/team-crest-vector.mjs';

const root='artifacts/team-crest-rollout', out='public/team-crests/vector-v1';
fs.mkdirSync(out,{recursive:true});
const read=file=>{const c={exports:{}};vm.runInNewContext(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,c);return c.exports;};
const files=[...fs.readFileSync('src/data/leagues/index.ts','utf8').matchAll(/from '\.\/([^']+)'/g)].map(m=>m[1]);
const previous=JSON.parse(fs.readFileSync(`${root}/manifest.json`,'utf8'));
if(!fs.existsSync(`${root}/image-generation-manifest.json`))fs.copyFileSync(`${root}/manifest.json`,`${root}/image-generation-manifest.json`);
const prior=new Map(previous.clubs.map(c=>[c.id,c]));
const pilots=new Set(['arsenal','chelsea','liverpool','manchester-city','manchester-united']);
const catalog={},clubs=[];
for(const file of files){
  const {CLUBS,LEAGUE_INFO}=read(`src/data/leagues/${file}.ts`);
  for(const club of CLUBS){
    if(!/^[a-z0-9-]+$/.test(club.id)||catalog[club.id])throw Error(`Invalid/duplicate ID: ${club.id}`);
    let {svg,shape,motif}=createVectorCrest(club);
    if(pilots.has(club.id)){
      svg=fs.readFileSync(`artifacts/team-crest-vector-examples/${club.id}.svg`,'utf8');
      shape='approved-pilot';motif='approved-pilot';
    }
    const hash=crypto.createHash('sha256').update(svg).digest('hex').slice(0,12);
    const runtime=`/team-crests/vector-v1/${club.id}.${hash}.svg`;
    fs.writeFileSync(`public${runtime}`,svg);
    catalog[club.id]=runtime;
    clubs.push({id:club.id,name:club.name,shortName:club.shortName,league:LEAGUE_INFO.id,color:club.color,secondaryColor:club.secondaryColor,
      format:'svg',shape,motif,sourceHash:hash,runtime,bytes:Buffer.byteLength(svg),status:'integrated',
      archivedImageSource:prior.get(club.id)?.archivedImageSource||prior.get(club.id)?.source});
  }
}
fs.writeFileSync('src/data/teamCrests.ts','// Generated by scripts/build-vector-team-crests.mjs. Local SVG assets keyed by stable club ID.\nexport const TEAM_CRESTS: Readonly<Record<string, string>> = '+JSON.stringify(catalog,null,2)+';\n');
fs.writeFileSync(`${root}/manifest.json`,JSON.stringify({version:2,generator:'authored-vector-system',rightsStatus:'No legal clearance claimed',clubs},null,2));
const report={total:clubs.length,integrated:clubs.length,pending:[],failures:[],bytes:clubs.reduce((n,c)=>n+c.bytes,0),format:'svg'};
fs.writeFileSync(`${root}/coverage.json`,JSON.stringify(report,null,2));
fs.writeFileSync(`${root}/checkpoint.json`,JSON.stringify({status:'All catalog clubs integrated as vectors; validation in progress',total:clubs.length,integrated:clubs.length},null,2));
console.log(JSON.stringify(report));
