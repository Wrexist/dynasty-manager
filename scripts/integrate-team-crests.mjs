import fs from 'node:fs';
import crypto from 'node:crypto';
import { chromium } from 'playwright';

const root = 'artifacts/team-crest-rollout';
const manifest = JSON.parse(fs.readFileSync(`${root}/manifest.json`, 'utf8'));
if (manifest.generator === 'authored-vector-system') throw Error('Raster workflow archived. Use scripts/build-vector-team-crests.mjs.');
const out = 'public/team-crests/v1';
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
const catalog = {};
const failures = [];
try {
  const page = await browser.newPage();
  for (const club of manifest.clubs) {
    if (!fs.existsSync(club.source)) continue;
    const bytes = fs.readFileSync(club.source);
    const hash = crypto.createHash('sha256').update(bytes).digest('hex').slice(0, 12);
    const filename = `${club.id}.${hash}.webp`;
    if (club.sourceHash === hash && club.runtime === `/${out.slice(7)}/${filename}` && fs.existsSync(`${out}/${filename}`)) {
      catalog[club.id] = club.runtime;
      continue;
    }
    const result = await page.evaluate(async data => {
      const img = new Image(); img.src = data; await img.decode();
      const canvas = document.createElement('canvas'); canvas.width = 256; canvas.height = 256;
      const ctx = canvas.getContext('2d');
      ctx.drawImage(img, 0, 0, 256, 256);
      const pixels = ctx.getImageData(0, 0, 256, 256).data;
      let transparent = 0, opaque = 0;
      for (let i = 3; i < pixels.length; i += 4) {
        if (pixels[i] === 0) transparent++;
        if (pixels[i] > 240) opaque++;
      }
      return { url: canvas.toDataURL('image/webp', 0.94), transparent: transparent / 65536,
        opaque: opaque / 65536, width: img.width, height: img.height };
    }, `data:image/png;base64,${bytes.toString('base64')}`);
    if (result.transparent < 0.08 || result.opaque < 0.15 || result.width !== result.height) {
      failures.push({ id: club.id, reason: 'Invalid dimensions or transparency', ...result, url: undefined });
      club.status = 'needs-revision'; continue;
    }
    const runtime = Buffer.from(result.url.split(',')[1], 'base64');
    fs.writeFileSync(`${out}/${filename}`, runtime);
    club.sourceHash = hash; club.runtime = `/team-crests/v1/${filename}`;
    club.bytes = runtime.length; club.transparent = result.transparent;
    club.status = 'integrated';
    catalog[club.id] = club.runtime;
  }
} finally { await browser.close(); }
fs.writeFileSync('src/data/teamCrests.ts', '// Generated by scripts/integrate-team-crests.mjs. Stable club IDs; locally bundled images.\nexport const TEAM_CRESTS: Readonly<Record<string, string>> = ' + JSON.stringify(catalog, null, 2) + ';\n');
fs.writeFileSync(`${root}/manifest.json`, JSON.stringify(manifest, null, 2));
const report = { total: manifest.clubs.length, integrated: Object.keys(catalog).length,
  pending: manifest.clubs.filter(c => !catalog[c.id]).map(c => c.id), failures,
  bytes: manifest.clubs.filter(c => catalog[c.id]).reduce((n, c) => n + c.bytes, 0) };
fs.writeFileSync(`${root}/coverage.json`, JSON.stringify(report, null, 2));
console.log(JSON.stringify({ ...report, pending: report.pending.length }));
if (failures.length) process.exitCode = 1;
